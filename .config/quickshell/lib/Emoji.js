function search(q, limit) {
    var words = String(q || "").toLowerCase().split(/\s+/).filter(function(w) { return w !== "" })
    var out = []
    for (var i = 0; i < LIST.length; i++) {
        var keys = LIST[i][1].split(" ")
        var ok = true
        for (var w = 0; w < words.length && ok; w++) {
            var hit = false
            for (var k = 0; k < keys.length; k++) if (keys[k].indexOf(words[w]) === 0) { hit = true; break }
            ok = hit
        }
        if (ok) out.push({ e: LIST[i][0], name: keys[0] })
        if (limit && out.length >= limit) break
    }
    return out
}

#!/bin/sh
# Writes hyprlock.conf from the current palette.
# Edit: the hyprlock.conf it prints here (layout, fonts, sizes).

mkdir -p "$HOME/.config/hypr"
pal=$(cat "$HOME/.cache/quickshell/apsis-palette" 2>/dev/null)

bg="17090F"; item="351421"; text="F6E9EF"; accent="EC4C78"; cyan="5AD1C8"

case "$pal" in
    navy)
        bg="0A0A3C"; item="1C2160"; text="F3ECF5"; accent="3AD6E0"; cyan="0FF0FC" ;;
    auto)
        j="$HOME/.cache/quickshell/apsis-auto.json"
        if [ -f "$j" ]; then
            get() { grep "\"$1\":" "$j" | head -1 | sed -E 's/.*"#?([0-9A-Fa-f]{6})".*/\1/'; }
            v=$(get bgMain);      [ -n "$v" ] && bg="$v"
            v=$(get bgItem);      [ -n "$v" ] && item="$v"
            v=$(get textPrimary); [ -n "$v" ] && text="$v"
            v=$(get accent);      [ -n "$v" ] && accent="$v"
            v=$(get cyan);        [ -n "$v" ] && cyan="$v"
        fi ;;
esac

cat > "$HOME/.config/hypr/hyprlock.conf" <<CONF
# Generated by apsis-hyprlock.sh from the current palette. Do not hand-edit.
background {
    monitor =
    color = rgba(${bg}ff)
}

input-field {
    monitor =
    size = 320, 52
    outline_thickness = 2
    dots_size = 0.25
    dots_spacing = 0.3
    dots_center = true
    outer_color = rgba(${accent}ff)
    inner_color = rgba(${item}ff)
    font_color = rgba(${text}ff)
    check_color = rgba(${cyan}ff)
    fail_color = rgba(ff6b81ff)
    placeholder_text = <span foreground="##${text}">Password</span>
    position = 0, -20
    halign = center
    valign = center
}

label {
    monitor =
    text = \$TIME
    color = rgba(${text}ff)
    font_size = 64
    font_family = JetBrainsMono Nerd Font
    position = 0, 140
    halign = center
    valign = center
}

label {
    monitor =
    text = \$USER
    color = rgba(${accent}ff)
    font_size = 16
    font_family = JetBrainsMono Nerd Font
    position = 0, 70
    halign = center
    valign = center
}
CONF

#!/bin/sh
# Writes dunstrc from the current palette and reloads dunst.
# Edit: the dunstrc it prints here (fonts, sizes, timeouts).

mkdir -p "$HOME/.config/dunst"
pal=$(cat "$HOME/.cache/quickshell/apsis-palette" 2>/dev/null)

card="210D15"; text="F6E9EF"; accent="EC4C78"; danger="FF6B81"
case "$pal" in
    navy) card="101445"; text="F3ECF5"; accent="3AD6E0"; danger="FF6B81" ;;
    auto)
        j="$HOME/.cache/quickshell/apsis-auto.json"
        if [ -f "$j" ]; then
            get() { grep "\"$1\":" "$j" | head -1 | sed -E 's/.*"#?([0-9A-Fa-f]{6})".*/\1/'; }
            v=$(get bgCard);      [ -n "$v" ] && card="$v"
            v=$(get textPrimary); [ -n "$v" ] && text="$v"
            v=$(get accent);      [ -n "$v" ] && accent="$v"
            v=$(get danger);      [ -n "$v" ] && danger="$v"
        fi ;;
esac

cat > "$HOME/.config/dunst/dunstrc" <<CONF
# Generated by apsis-dunst.sh from the current palette. Do not hand-edit.
[global]
    origin = top-right
    offset = (12, 48)
    frame_width = 1
    corner_radius = 12
    font = JetBrainsMono Nerd Font 10
    format = "<b>%s</b>\n%b"
    markup = full
    padding = 12
    horizontal_padding = 14

[urgency_low]
    background = "#${card}"
    foreground = "#${text}"
    frame_color = "#${accent}"
    timeout = 5

[urgency_normal]
    background = "#${card}"
    foreground = "#${text}"
    frame_color = "#${accent}"
    timeout = 8

[urgency_critical]
    background = "#${card}"
    foreground = "#${text}"
    frame_color = "#${danger}"
    timeout = 0
CONF

command -v dunstctl >/dev/null 2>&1 && dunstctl reload >/dev/null 2>&1 || true

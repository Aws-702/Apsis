#!/bin/sh
# Idle handling through hypridle: lock, screen off, optional suspend, from Settings > Desktop > Idle.
# Usage: apsis-idle.sh start|apply|pause|resume|status|print. Edit: the listeners it writes here.

settings="${XDG_STATE_HOME:-$HOME/.local/state}/apsis/settings.json"
conf="$HOME/.config/hypr/hypridle.conf"
scripts="$HOME/.config/hypr/scripts"
paused="$HOME/.cache/apsis/idle-paused"
train="$HOME/.cache/apsis/train"

num() {
    v=$(jq -r --arg k "$1" '.[$k] // empty' "$settings" 2>/dev/null)
    case "$v" in ''|*[!0-9]*) v="$2" ;; esac
    printf '%s' "$v"
}
enabled() {
    [ "$(jq -r '.idleEnabled // true' "$settings" 2>/dev/null)" != "false" ]
}

config() {
    lock=$(num idleLockMin 10)
    screen=$(num idleScreenMin 15)
    sleepm=$(num idleSleepMin 0)
    cat <<CONF
# Generated by apsis-idle.sh from Settings > Desktop > Idle. Do not hand-edit.
general {
    lock_cmd = $scripts/apsis-lock.sh
    before_sleep_cmd = loginctl lock-session
    after_sleep_cmd = $scripts/apsis-screen.sh on
}
CONF
    if [ "$lock" -gt 0 ]; then cat <<CONF

# lock
listener {
    timeout = $((lock * 60))
    on-timeout = loginctl lock-session
}
CONF
    fi
    if [ "$screen" -gt 0 ]; then cat <<CONF

# screens off (any key or movement brings them back)
listener {
    timeout = $((screen * 60))
    on-timeout = $scripts/apsis-screen.sh off
    on-resume = $scripts/apsis-screen.sh on
}
CONF
    fi
    if [ "$sleepm" -gt 0 ]; then cat <<CONF

# sleep, but never in the middle of a Training mode run
listener {
    timeout = $((sleepm * 60))
    on-timeout = [ -f "$train" ] || systemctl suspend
}
CONF
    fi
}

stop() { pkill -x hypridle 2>/dev/null; return 0; }
run() {
    command -v hypridle >/dev/null 2>&1 || return 1
    stop
    config > "$conf"
    setsid -f hypridle -c "$conf" >/dev/null 2>&1
}

mkdir -p "$(dirname "$paused")" "$(dirname "$conf")"
case "${1:-}" in
    start)
        rm -f "$paused"
        if enabled; then run; else stop; fi ;;
    apply)
        if [ -f "$paused" ] || ! enabled; then stop; else run; fi ;;
    pause)  : > "$paused"; stop ;;
    resume) rm -f "$paused"; if enabled; then run; fi ;;
    status)
        if ! enabled; then echo off
        elif [ -f "$paused" ]; then echo paused
        elif pgrep -x hypridle >/dev/null 2>&1; then echo on
        else echo off; fi ;;
    print) config ;;
    *) echo "usage: $0 start | apply | pause | resume | status | print" >&2; exit 2 ;;
esac
